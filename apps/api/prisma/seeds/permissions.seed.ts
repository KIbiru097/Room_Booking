export async function seedSystemPermissions(prisma: PrismaClient) {
  for (const [module, action] of SYSTEM_PERMISSIONS) {
    const key = `${module}.${action}`;
    await prisma.permission.upsert({
      where: { key },
      update: { module, action, isSystem: true },
      create: {
        key,
        module,
        action,
        isSystem: true,
        description: `${action.replaceAll('_', ' ')} ${module}`,
      },
    });
  }
}
